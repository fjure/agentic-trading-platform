from pathlib import Path


def test_paper_http_sql_runtime_chain():
    from tests.integration.test_paper_commands import run_isolated_guest

    run_isolated_guest(Path(__file__), "PASS paper HTTP SQL runtime chain")


def guest():
    import json
    import os
    import sys
    import tempfile
    from datetime import UTC, datetime
    from types import SimpleNamespace

    import httpx
    from alembic import command
    from alembic.config import Config
    from fastapi.testclient import TestClient
    from sqlalchemy import URL, create_engine, event, text

    from services.control_api.app import create_app
    from services.control_api.auth import LocalAuth
    from services.control_api.paper_client import PaperClient
    from services.control_api.paper_commands import PaperCommands
    from services.execution.paper_credentials import PaperGenerationReader
    from services.execution.paper_verification import PaperAccountVerifier
    from services.runtime.paper_api import create_private_paper_app
    from services.runtime.paper_verification import PaperVerificationRuntime
    from services.setup import client as setup_client_module
    from services.setup.app import create_app as setup_app
    from services.setup.store import ProviderStore, generation_filename

    configuration = json.loads(sys.stdin.read())
    url = URL.create(
        "postgresql+psycopg",
        username=configuration["role"],
        password=configuration["password"],
        host="postgres",
        database=configuration["database"],
    )
    admin = create_engine(url, hide_parameters=True)
    migration = Config("alembic.ini")
    with admin.begin() as c:
        migration.attributes["connection"] = c
        command.upgrade(migration, "head")
        c.execute(text("REVOKE USAGE ON SCHEMA public FROM PUBLIC"))

    engines = []

    def role_engine(role):
        engine = create_engine(url, hide_parameters=True)
        engines.append(engine)

        @event.listens_for(engine, "connect")
        def assign(connection, _):
            connection.execute("SET ROLE " + role)
            connection.commit()

        return engine

    commands = PaperCommands(role_engine("atl_paper_control_api"))
    execution_commands = PaperCommands(role_engine("atl_paper_execution"))
    private_api = create_private_paper_app(commands)
    relayed_paths = []

    def relay(app, host, *, fail_after_publish=False):
        # Every response is generated by the actual ASGI application, never an API fixture.
        def handle(request):
            assert request.url.host == host.split(":")[0]
            relayed_paths.append((request.method, request.url.host, request.url.path))
            with TestClient(app, base_url="http://" + host, client=("127.0.0.1", 46001)) as http:
                response = http.request(
                    request.method,
                    str(request.url),
                    content=request.content,
                    headers=dict(request.headers),
                )
            if fail_after_publish and provider["lose_setup_response"]:
                provider["lose_setup_response"] = False
                raise httpx.ReadError("synthetic response loss")
            return httpx.Response(
                response.status_code, headers=dict(response.headers), content=response.content
            )

        return httpx.MockTransport(handle)

    paper = PaperClient(transport=relay(private_api, "paper-api:8012"))
    provider = {"mode": "ok", "hook": None, "lose_setup_response": False}
    provider_calls = []
    public_responses = []
    first_account = "12345678-1234-4234-8234-123456789012"
    other_account = "12345678-1234-4234-8234-123456789013"
    origin = "http://127.0.0.1:8000"
    canaries = []

    with tempfile.TemporaryDirectory(prefix="paper-chain-") as temporary:
        root = Path(temporary)
        os.chmod(root, 0o700)
        for name in ("alpaca", "jev"):
            (root / name).mkdir(mode=0o700)
        store = ProviderStore(root, owner_uid=os.getuid())
        setup_transport = relay(setup_app(store), "provider-setup:8011", fail_after_publish=True)
        real_httpx = httpx
        setup_client_module.httpx = SimpleNamespace(
            Client=lambda **kwargs: real_httpx.Client(transport=setup_transport, **kwargs)
        )
        auth = LocalAuth()
        normal_api = create_app(
            auth=auth, paper=paper, setup=setup_client_module.FixedSetupClient()
        )
        public = TestClient(
            normal_api, base_url=origin, client=("127.0.0.1", 46000), raise_server_exceptions=False
        )
        session = public.post(
            "/api/v1/session",
            json={"activationCode": auth.issue_activation_code()},
            headers={"Origin": origin, "Idempotency-Key": "chain-session-key1"},
        )
        assert session.status_code == 204

        def request(method, path, body=None, key="chain-default-key1"):
            headers = {"Origin": origin, "Idempotency-Key": key}
            response = public.request(method, path, json=body, headers=headers)
            public_responses.append(response.text)
            return response

        def save(generation, key=None):
            api_key = f"synthetic-chain-canary-key-{generation}"
            api_secret = f"synthetic-chain-canary-secret-{generation}"
            canaries.extend([api_key, api_secret])
            return request(
                "PUT",
                "/api/v1/integrations/alpaca",
                {
                    "apiKey": api_key,
                    "apiSecret": api_secret,
                    "expectedAccountId": first_account,
                    "paperOnly": True,
                },
                key or f"chain-save-key-{generation:04d}",
            )

        def verify(generation, key):
            response = request(
                "POST", "/api/v1/paper/verify-connection", {"credentialGeneration": generation}, key
            )
            assert response.status_code == 202, "verification receipt missing"
            assert response.json()["status"] == "ACCEPTED"
            return response.json()["operationId"]

        def operation(operation_id):
            response = request("GET", "/api/v1/paper/operations/" + operation_id)
            assert response.status_code == 200
            return response.json()

        def identity():
            with admin.connect() as c:
                return tuple(
                    c.execute(
                        text(
                            "SELECT active_generation,pending_generation,"
                            "pinned_account_id::text FROM public.paper_workflow_state"
                        )
                    ).one()
                )

        def provider_http(request):
            assert request.method == "GET"
            assert request.url.host in {"paper-api.alpaca.markets", "data.alpaca.markets"}
            provider_calls.append((request.method, request.url.host, request.url.path))
            assert request.headers["APCA-API-KEY-ID"].startswith("synthetic-chain-canary-key-")
            assert request.headers["APCA-API-SECRET-KEY"].startswith(
                "synthetic-chain-canary-secret-"
            )
            if request.url.path == "/v2/account":
                hook, provider["hook"] = provider["hook"], None
                if hook is not None:
                    hook()
                if provider["mode"] == "denied":
                    return httpx.Response(401, json={"message": "synthetic-provider-secret-canary"})
                if provider["mode"] == "unavailable":
                    return httpx.Response(503, json={"message": "synthetic-provider-secret-canary"})
                return httpx.Response(
                    200,
                    json={
                        "id": other_account if provider["mode"] == "wrong" else first_account,
                        "currency": "USD",
                        "status": "ACTIVE",
                        "account_blocked": False,
                        "trading_blocked": False,
                        "trade_suspended_by_user": False,
                        "cash": "100000.12",
                        "untrustedDebug": "synthetic-provider-secret-canary",
                    },
                )
            assert request.url.path == "/v2/stocks/quotes/latest"
            assert request.url.params == httpx.QueryParams({"symbols": "SPY,QQQ", "feed": "iex"})
            quote = {"bp": "100", "ap": "100.01", "t": datetime.now(UTC).isoformat()}
            return httpx.Response(200, json={"quotes": {"SPY": quote, "QQQ": quote}})

        def verifier_factory(**kwargs):
            return PaperAccountVerifier(transport=httpx.MockTransport(provider_http), **kwargs)

        runtime = PaperVerificationRuntime(
            commands=execution_commands,
            reader_factory=lambda: PaperGenerationReader(root, owner_uid=os.getuid()),
            verifier_factory=verifier_factory,
        )
        assert runtime.tick() == "READY" and provider_calls == []
        assert save(1).status_code == 200
        assert provider_calls == [] and (root / "alpaca" / generation_filename(1)).is_file()
        first = verify(1, "chain-verify-key01")
        replay = request(
            "POST",
            "/api/v1/paper/verify-connection",
            {"credentialGeneration": 1},
            "chain-verify-key01",
        )
        assert replay.status_code == 202 and replay.json()["operationId"] == first
        runtime.tick()
        assert operation(first)["status"] == "SUCCEEDED"
        assert identity() == (1, None, first_account)
        status = request("GET", "/api/v1/paper/status").json()
        assert status["setupState"] == "VERIFIED" and status["cash"] == "100000.12"
        assert status["entryGateOpen"] is False
        with admin.connect() as c:
            assert c.execute(text("SELECT count(*) FROM public.accounts")).scalar_one() == 0
            assert c.execute(text("SELECT count(*) FROM public.paper_commands")).scalar_one() == 1

        assert save(2).status_code == 200
        provider["mode"] = "wrong"
        wrong = verify(2, "chain-verify-wrong")
        runtime.tick()
        assert operation(wrong)["errorCode"] == "ACCOUNT_IDENTITY_MISMATCH"
        assert identity() == (1, 2, first_account)
        provider["mode"] = "denied"
        denied = verify(2, "chain-verify-deny1")
        runtime.tick()
        assert operation(denied)["errorCode"] == "CREDENTIALS_INVALID"
        assert identity() == (1, 2, first_account)

        provider["mode"] = "unavailable"
        unavailable = verify(2, "chain-verify-fail1")
        runtime.tick()
        assert operation(unavailable)["errorCode"] == "PROVIDER_UNAVAILABLE"
        assert identity() == (1, 2, first_account)

        provider["mode"] = "ok"
        stale = verify(2, "chain-verify-stale")

        def rotate_during_io():
            assert save(3).status_code == 200

        provider["hook"] = rotate_during_io
        runtime.tick()
        assert operation(stale)["errorCode"] == "VERSION_CONFLICT"
        assert identity() == (1, 3, first_account)

        # Lost setup reply after immutable file publication leaves a recoverable pending allocation.
        provider["lose_setup_response"] = True
        failed_save = save(4, "chain-save-crash1")
        assert failed_save.status_code == 503
        assert identity() == (1, 4, first_account)
        assert save(4, "chain-save-crash1").status_code == 200
        with admin.connect() as c:
            assert (
                c.execute(
                    text("SELECT saved_generation FROM public.paper_workflow_state")
                ).scalar_one()
                == 4
            )

        killed = verify(4, "chain-verify-kill1")

        def kill_during_io():
            kill = request("POST", "/api/v1/paper/control", {"action": "KILL"}, "chain-kill-key001")
            assert kill.status_code == 202
            assert request("GET", "/api/v1/paper/status").json()["operatingState"] == "HALTED"

        provider["hook"] = kill_during_io
        runtime.tick()
        assert operation(killed)["errorCode"] == "KILL_SWITCH_ACTIVE"
        assert identity() == (1, 4, first_account)
        calls = len(provider_calls)
        runtime.tick()
        assert len(provider_calls) == calls  # The queued KILL never reads keys or calls a provider.
        assert (root / "alpaca" / generation_filename(1)).is_file()

        with admin.connect() as c:
            audit = json.dumps(
                c.execute(
                    text(
                        "SELECT coalesce(jsonb_agg(to_jsonb(e)),'[]'::jsonb) "
                        "FROM public.paper_command_events e"
                    )
                ).scalar_one()
            )
            receipts = json.dumps(
                c.execute(
                    text(
                        "SELECT coalesce(jsonb_agg(to_jsonb(e)),'[]'::jsonb) "
                        "FROM public.paper_rotation_receipts e"
                    )
                ).scalar_one()
            )
            commands_json = json.dumps(
                c.execute(
                    text(
                        "SELECT coalesce(jsonb_agg(to_jsonb(e)),'[]'::jsonb) "
                        "FROM public.paper_commands e"
                    )
                ).scalar_one()
            )
        observed = " ".join(public_responses) + audit + receipts + commands_json
        for canary in [*canaries, "synthetic-provider-secret-canary", first_account, other_account]:
            assert canary not in observed
        assert any(path == "/commands" for _, _, path in relayed_paths)
        assert any("/integrations/alpaca/generations/" in path for _, _, path in relayed_paths)
    for engine in engines:
        engine.dispose()
    admin.dispose()
    print("PASS paper HTTP SQL runtime chain")


if __name__ == "__main__":
    guest()
